  const translationEntries = Object.entries(translations);
  const deskTranslationsStart = translationEntries.findIndex(([key]) => key === "Muhtasari");
  const englishToSwahili = Object.fromEntries(
    translationEntries.slice(0, deskTranslationsStart)
      .filter(([key]) => key !== "Maombi yote")
      .map(([english, swahili]) => [english.trim(), swahili.trim()])
  );
  const swahiliToEnglish = Object.fromEntries(
    translationEntries.slice(0, deskTranslationsStart).map(([english, swahili]) => [swahili.trim(), english.trim()])
  );
  swahiliToEnglish["Maombi yote"] = "All requests";
  Object.assign(swahiliToEnglish, Object.fromEntries(
    translationEntries.slice(deskTranslationsStart).map(([swahili, english]) => [swahili.trim(), english.trim()])
  ));

  const originals = new WeakMap();
  const originalAttributes = new WeakMap();
  let language = "en";
  let translating = false;
  let originalTitle = "";

  function translateValue(value) {
    const leadingWhitespace = value.match(/^\s*/)?.[0] || "";
    const trailingWhitespace = value.match(/\s*$/)?.[0] || "";
    const trimmedValue = value.trim();
    let translated = language === "sw"
      ? englishToSwahili[trimmedValue]
      : swahiliToEnglish[trimmedValue];
    if (!translated && language === "sw") {
      let match = trimmedValue.match(/^Only (\d+) left$/);
      if (match) translated = `Zimebaki ${match[1]} tu`;
      match = trimmedValue.match(/^Showing (\d+) of (\d+) products$/);
      if (match) translated = `Inaonyesha ${match[1]} kati ya ${match[2]} bidhaa`;
      match = trimmedValue.match(/^(\d+) picks · (.+)$/);
      if (match) translated = `${match[1]} chaguo · ${englishToSwahili[match[2]] || match[2]}`;
      if (trimmedValue === "＋ Add to bag") translated = "＋ Ongeza kikapuni";
      match = trimmedValue.match(/^([0-9.]+) · (\d+) reviews$/);
      if (match) translated = `${match[1]} · ${match[2]} maoni`;
      if (trimmedValue === "HOT") translated = "MOTO";
    } else if (!translated && language === "en") {
      let match = trimmedValue.match(/^Zimebaki (\d+) tu$/);
      if (match) translated = `Only ${match[1]} left`;
      match = trimmedValue.match(/^Inaonyesha (\d+) kati ya (\d+) bidhaa$/);
      if (match) translated = `Showing ${match[1]} of ${match[2]} products`;
      match = trimmedValue.match(/^(\d+) chaguo · (.+)$/);
      if (match) translated = `${match[1]} picks · ${swahiliToEnglish[match[2]] || match[2]}`;
      if (trimmedValue === "＋ Ongeza kikapuni") translated = "＋ Add to bag";
      match = trimmedValue.match(/^([0-9.]+) · (\d+) maoni$/);
      if (match) translated = `${match[1]} · ${match[2]} reviews`;
      if (trimmedValue === "MOTO") translated = "HOT";
    }
    return translated ? `${leadingWhitespace}${translated}${trailingWhitespace}` : value;
  }

  function translateNode(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      if (!originals.has(node)) originals.set(node, node.nodeValue);
      node.nodeValue = translateValue(originals.get(node));
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    const attributes = ["placeholder", "aria-label", "title", "alt"];
    let saved = originalAttributes.get(node);
    if (!saved) {
      saved = new Map();
      originalAttributes.set(node, saved);
    }
    for (const name of attributes) {
      if (!node.hasAttribute(name)) continue;
      if (!saved.has(name)) saved.set(name, node.getAttribute(name));
      node.setAttribute(name, translateValue(saved.get(name)));
    }
    node.childNodes.forEach(translateNode);
  }

  function applyLanguage(nextLanguage) {
    language = nextLanguage === "sw" ? "sw" : "en";
    translating = true;
    document.documentElement.lang = language;
    if (originalTitle) document.title = translateValue(originalTitle);
    document.querySelectorAll("[data-language-toggle]").forEach(button => {
      button.setAttribute("aria-label", language === "en" ? "Switch language to Kiswahili" : "Switch language to English");
      const code = button.querySelector(".language-code");
      if (code) code.textContent = language === "en" ? "SW" : "EN";
      const label = button.querySelector(".language-label");
      if (label) label.textContent = language === "en" ? "Translate" : "Tafsiri";
    });
    document.body.childNodes.forEach(translateNode);
    document.querySelectorAll("[data-language-toggle]").forEach(button => {
      button.setAttribute("aria-label", language === "en" ? "Switch language to Kiswahili" : "Switch language to English");
    });
    localStorage.setItem("noah-language", language);
    translating = false;
  }

  window.initNoahTranslations = ({ defaultLanguage = "en" } = {}) => {
    originalTitle = document.title;
    const savedLanguage = localStorage.getItem("noah-language");
    applyLanguage(savedLanguage || defaultLanguage);
    document.querySelectorAll("[data-language-toggle]").forEach(button => {
      button.addEventListener("click", () => applyLanguage(language === "en" ? "sw" : "en"));
    });
    const observer = new MutationObserver(records => {
      if (translating) return;
      translating = true;
      for (const record of records) {
        if (record.type === "childList") record.addedNodes.forEach(translateNode);
      }
      translating = false;
    });
    observer.observe(document.body, { childList: true, subtree: true });
    window.addEventListener("storage", event => {
      if (event.key === "noah-language" && event.newValue) applyLanguage(event.newValue);
    });
  };
  window.translateNoahText = value => {
    if (language === "sw" && value.endsWith(" — Business Desk")) return value.replace(" — Business Desk", " — Dawati la Biashara");
    if (language === "en" && value.endsWith(" — Dawati la Biashara")) return value.replace(" — Dawati la Biashara", " — Business Desk");
    return translateValue(value);
  };
